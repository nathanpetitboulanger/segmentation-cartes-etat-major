import torch
from torch import nn
import matplotlib.pyplot as plt

# Create a convolutional neural network
class Unet1(nn.Module):
    def __init__(self):
        super().__init__()
        self.block_1 = nn.Sequential(
            nn.Conv2d(in_channels=3,
                      out_channels=64,
                      kernel_size=3, # how big is the square that's going over the image?
                      stride=1, # default
                      padding=0),# options = "valid" (no padding) or "same" (output has same shape as input) or int for specific number
            nn.ReLU(),
            nn.Conv2d(in_channels=64,
                      out_channels=64,
                      kernel_size=3,
                      stride=1,
                      padding=0),
            nn.ReLU()
            )
        self.block_2 = nn.Sequential(
            nn.MaxPool2d(kernel_size=2,
                         stride=2), # default stride value is same as kernel_size
            nn.Conv2d(in_channels=64,
                      out_channels=128,
                      kernel_size=3,
                      stride=1,
                      padding=0),
            nn.ReLU(),
            nn.Conv2d(in_channels=128,
                      out_channels=128,
                      kernel_size=3,
                      stride=1,
                      padding=0),
            nn.ReLU(),
            )
        self.block_3 = nn.Sequential(
            nn.MaxPool2d(kernel_size=2,
                         stride=2),
            nn.Conv2d(in_channels=128,
                      out_channels=256,
                      kernel_size=3,
                      stride=1,
                      padding=0),
            nn.ReLU(),
            nn.Conv2d(in_channels=256,
                      out_channels=256,
                      kernel_size=3,
                      stride=1,
                      padding=0),
            nn.ReLU(),
            )
        self.block_4 = nn.Sequential(
            nn.MaxPool2d(kernel_size=2,
                         stride=2),
            nn.Conv2d(in_channels=256,
                      out_channels=512,
                      kernel_size=3,
                      stride=1,
                      padding=0),
            nn.ReLU(),
            nn.Conv2d(in_channels=512,
                      out_channels=512,
                      kernel_size=3,
                      stride=1,
                      padding=0),
            nn.ReLU(),
            )
        self.block_5 = nn.Sequential(
            nn.MaxPool2d(kernel_size=2,
                         stride=2),
            nn.Conv2d(in_channels=512,
                      out_channels=1024,
                      kernel_size=3,
                      stride=1,
                      padding=0),
            nn.ReLU(),
            nn.Conv2d(in_channels=1024,
                      out_channels=1024,
                      kernel_size=3,
                      stride=1,
                      padding=0),
            nn.ReLU(),
            nn.ConvTranspose2d(1024, 512, kernel_size=2, stride=2)
            )
        self.block_6 = nn.Sequential(
            nn.Conv2d(in_channels=1024,
                      out_channels=512,
                      kernel_size=3,
                      stride=1,
                      padding=0),
            nn.ReLU(),
            nn.Conv2d(in_channels=512,
                      out_channels=512,
                      kernel_size=3,
                      stride=1,
                      padding=0),
            nn.ReLU(),
            nn.ConvTranspose2d(512, 256, kernel_size=2, stride=2)
            )
        self.block_7 = nn.Sequential(
            nn.Conv2d(in_channels=512,
                      out_channels=256,
                      kernel_size=3,
                      stride=1,
                      padding=0),
            nn.ReLU(),
            nn.Conv2d(in_channels=256,
                      out_channels=256,
                      kernel_size=3,
                      stride=1,
                      padding=0),
            nn.ReLU(),
            nn.ConvTranspose2d(256, 128, kernel_size=2, stride=2)
            )
        self.block_8 = nn.Sequential(
            nn.Conv2d(in_channels=256,
                      out_channels=128,
                      kernel_size=3,
                      stride=1,
                      padding=0),
            nn.ReLU(),
            nn.Conv2d(in_channels=128,
                      out_channels=128,
                      kernel_size=3,
                      stride=1,
                      padding=0),
            nn.ReLU(),
            nn.ConvTranspose2d(128, 64, kernel_size=2, stride=2)
            )
        self.block_9 = nn.Sequential(
            nn.Conv2d(in_channels=128,
                      out_channels=64,
                      kernel_size=3,
                      stride=1,
                      padding=0),
            nn.ReLU(),
            nn.Conv2d(in_channels=64,
                      out_channels=64,
                      kernel_size=3,
                      stride=1,
                      padding=0),
            nn.ReLU(),
            nn.Conv2d(in_channels=64,
                      out_channels=10, # mettre nombre de classe
                      kernel_size=1,
                      stride=1,
                      padding="same")
            )

    def forward(self, x: torch.Tensor):
        print(x.shape)
        x1 = self.block_1(x)
        print(x1.shape)
        x2 = self.block_2(x1)
        print(x2.shape)
        x3 = self.block_3(x2)
        print(x3.shape)
        x4 = self.block_4(x3)
        print(x4.shape)
        x5 = self.block_5(x4)
        print(x5.shape)
        x5 = torch.cat([x5, x4[:, :, 4:-4, 4:-4]], 1) # on adapte la shape de x4 pour correspondre a x6
        print(x5.shape)
        x6 = self.block_6(x5)
        print(x6.shape)
        x6 = torch.cat([x6, x3[:, :, 16:-16, 16:-16]], 1)
        print(x6.shape)
        x7 = self.block_7(x6)
        print(x7.shape)
        x7 = torch.cat([x7, x2[:, :, 40:-40, 40:-40]], 1)
        print(x7.shape)
        x8 = self.block_8(x7)
        print(x8.shape)
        x8 = torch.cat([x8, x1[:, :, 88:-88, 88:-88]], 1)
        print(x8.shape)
        x9 = self.block_9(x8)
        print(x9.shape)
        return x9

torch.manual_seed(42)
model_1 = Unet1()
